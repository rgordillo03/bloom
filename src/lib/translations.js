// Small helper — supports {name} placeholders.
// Usage: fill(t.settings.removeMemberConfirm, { name: 'Ronja' })
export function fill(template, values = {}) {
  if (!template) return '';
  return Object.entries(values).reduce(
    (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
    template
  );
}
